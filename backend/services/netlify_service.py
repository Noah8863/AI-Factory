"""
services/netlify_service.py
────────────────────────────
Netlify Manager — programmatically creates and configures Netlify sites
for every frontend/full-stack project generated by AI Factory.

Public API
──────────
  create_netlify_site(site_name, repo_full_name, is_full_stack)
      Creates a Netlify site linked to a GitHub repo with build settings
      (build command: 'npm run build', publish directory: 'dist').
      For full-stack projects, also commits a netlify.toml to the repo
      with a placeholder backend URL that the user fills in after they
      deploy their generated project's backend.
      Returns {"site_url": str, "site_id": str} on success, None on failure.

  write_netlify_toml(repo_name)
      Commits a netlify.toml to the root of a generated repo.
      Called automatically by create_netlify_site for full-stack projects.

IMPORTANT — why we use a placeholder backend URL
─────────────────────────────────────────────────
Every generated full-stack project has its OWN backend that the user must
deploy separately (e.g. to Railway).  At the time netlify.toml is written,
that backend has not been deployed yet — there is no URL to embed.

We must NOT use the AI Factory's own Railway URL here.  Doing so would
route the generated project's API calls into AI Factory's database,
polluting it with data that belongs to the generated app.

Instead we write a clearly-marked placeholder and instruct the user (via
the generated README) to replace it with their backend's real URL once
they have one.
"""

import logging
import os

import requests
from dotenv import load_dotenv

load_dotenv()

logger = logging.getLogger(__name__)


def _auth_token() -> str:
    return os.getenv("NETLIFY_AUTH_TOKEN", "")


def _api_base() -> str:
    return os.getenv("NETLIFY_API_BASE_URL", "https://api.netlify.com/api/v1").rstrip("/")


def _headers() -> dict:
    return {
        "Authorization": f"Bearer {_auth_token()}",
        "Content-Type": "application/json",
    }


# ── netlify.toml generation ───────────────────────────────────────────────────

# Placeholder written into the generated repo's netlify.toml.
# The user replaces this after deploying their generated project's backend.
_BACKEND_URL_PLACEHOLDER = "https://YOUR_BACKEND_URL_HERE"

def _render_netlify_toml() -> str:
    """
    Render a netlify.toml that:
      - Sets the frontend build command and publish directory.
      - Proxies /api/* requests to the generated project's backend.

    The `to` field uses a placeholder URL because the generated project's
    backend has not been deployed yet at generation time.  The user must
    replace BACKEND_URL_HERE with their actual backend URL after deploying.

    The proxy redirect (status 200, force true) rewrites requests server-side,
    so the browser never sees a cross-origin request — eliminating CORS issues
    for full-stack deployments where the frontend is on Netlify and the backend
    is on Railway (or any other host).
    """
    return (
        "[build]\n"
        '  command = "npm run build"\n'
        '  publish = "dist"\n'
        "\n"
        "# ─────────────────────────────────────────────────────────────────────\n"
        "# ACTION REQUIRED: replace the placeholder URL below with the real URL\n"
        "# of YOUR deployed backend before your frontend will work correctly.\n"
        "#\n"
        "# Example (Railway):\n"
        "#   to = \"https://my-app-backend.up.railway.app/api/:splat\"\n"
        "# ─────────────────────────────────────────────────────────────────────\n"
        "[[redirects]]\n"
        '  from   = "/api/*"\n'
        f'  to     = "{_BACKEND_URL_PLACEHOLDER}/api/:splat"\n'
        "  status = 200\n"
        "  force  = true\n"
    )


def write_netlify_toml(repo_name: str) -> bool:
    """
    Commit a netlify.toml to the root of a generated GitHub repo.

    Called automatically by create_netlify_site for full-stack projects.
    The backend URL in the proxy rule is a placeholder — the user fills
    it in after deploying their generated project's own backend.

    Returns True on success, False on failure.
    """
    from services.github_service import write_file_to_repo

    toml = _render_netlify_toml()
    ok = write_file_to_repo(
        repo_name=repo_name,
        file_path="netlify.toml",
        content=toml,
        branch="main",
        commit_message="AI Agent: add netlify.toml (update backend URL before deploying)",
    )
    if ok:
        logger.info(
            "netlify.toml committed to %s (backend URL is a placeholder — user must update).",
            repo_name,
        )
    else:
        logger.warning("Failed to write netlify.toml to %s.", repo_name)
    return ok


# ── Site creation ─────────────────────────────────────────────────────────────

def create_netlify_site(
    site_name: str,
    repo_full_name: str,
    is_full_stack: bool = False,
) -> dict | None:
    """
    Create a Netlify site linked to the GitHub repo, configured for CD.

    Netlify will trigger a new deploy on every push to the main branch.
    Build settings: command='npm run build', publish directory='dist'.

    For full-stack projects a netlify.toml is also committed to the repo.
    It contains a /api/* proxy redirect with a placeholder backend URL.
    The user must replace that placeholder after deploying their generated
    project's own backend — see the generated README for instructions.

    Args:
        site_name:       Desired Netlify subdomain slug (e.g. "recipe-app").
                         Netlify appends .netlify.app → https://recipe-app.netlify.app
                         If the name is already taken, falls back to an auto-assigned name.
        repo_full_name:  GitHub "org/repo" identifier
                         (e.g. "AI-Factory-Repos/recipe-app").
        is_full_stack:   When True, commits a netlify.toml with an /api/* proxy stub.

    Returns:
        {"site_url": str, "site_id": str}  on success.
        None                                on failure.
    """
    token = _auth_token()
    if not token:
        logger.error(
            "NETLIFY_AUTH_TOKEN is not set — skipping Netlify site creation for %s.",
            site_name,
        )
        return None

    team_id = os.getenv("NETLIFY_TEAM_ID", "")

    payload: dict = {
        "name": site_name,
        "repo": {
            "provider": "github",
            "repo": repo_full_name,
            "branch": "main",
            "cmd": "npm run build",
            "dir": "dist",
        },
    }
    # account_slug scopes the site to a Netlify team; omit for personal accounts.
    if team_id:
        payload["account_slug"] = team_id

    url = f"{_api_base()}/sites"
    logger.info(
        "Creating Netlify site '%s' linked to %s (team=%s) …",
        site_name, repo_full_name, team_id or "personal",
    )

    try:
        resp = requests.post(url, json=payload, headers=_headers(), timeout=30)
    except requests.RequestException as exc:
        logger.error("Netlify API request failed for '%s': %s", site_name, exc)
        return None

    if resp.status_code in (200, 201):
        data = resp.json()
        site_id  = data.get("id", "")
        # Prefer the HTTPS URL; fall back to a deterministic subdomain URL.
        site_url = data.get("ssl_url") or data.get("url") or f"https://{site_name}.netlify.app"

        logger.info(
            "Netlify site created: %s (id=%s, repo=%s).",
            site_url, site_id, repo_full_name,
        )

        # For full-stack projects: commit netlify.toml with the proxy stub.
        # The backend URL is a placeholder — the user updates it after deploying
        # their generated project's backend.
        if is_full_stack:
            repo_name = repo_full_name.split("/")[-1]
            write_netlify_toml(repo_name)

        return {"site_url": site_url, "site_id": site_id}

    # Handle name conflict — Netlify returns 422 when the subdomain is taken.
    if resp.status_code == 422:
        logger.warning(
            "Netlify site name '%s' already taken (422). "
            "Attempting creation without explicit name so Netlify auto-assigns one.",
            site_name,
        )
        payload.pop("name", None)
        try:
            retry = requests.post(url, json=payload, headers=_headers(), timeout=30)
        except requests.RequestException as exc:
            logger.error("Netlify retry request failed for '%s': %s", site_name, exc)
            return None

        if retry.status_code in (200, 201):
            data = retry.json()
            site_id  = data.get("id", "")
            site_url = data.get("ssl_url") or data.get("url") or ""
            logger.info(
                "Netlify site created (auto-name): %s (id=%s).", site_url, site_id,
            )
            if is_full_stack:
                repo_name = repo_full_name.split("/")[-1]
                write_netlify_toml(repo_name)
            return {"site_url": site_url, "site_id": site_id}

    logger.error(
        "Failed to create Netlify site '%s': %s %s",
        site_name, resp.status_code, resp.text[:400],
    )
    return None
